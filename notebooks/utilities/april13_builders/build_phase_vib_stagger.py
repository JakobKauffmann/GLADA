"""
Builds phase_vib_stagger.ipynb — a single-shot Colab notebook that tests
two architectural fixes for the GLADA negative-transfer finding:

  1. Per-group VIB: compress each group representation g_k -> z_k via its own
     VIB BEFORE the per-group discriminator sees it. Currently VIB sits on the
     pooled global representation, AFTER the discriminators have already
     fought over uncompressed group features. The reviewer feedback: the
     discriminators are cannibalizing each other's gradients on raw features.

  2. Staggered activation: introduce the 5 auxiliary signals (VIB, per-group
     GLADA, speaker adversary, CKA) one at a time across Phase 2, rather than
     all firing simultaneously when the backbone unfreezes. Reviewer feedback:
     "5 signals at once with the backbone unfreezing is too much at once."

Configs trained:
  A. per_group_vib            — fix 1 only
  B. staggered                — fix 2 only
  C. per_group_vib_staggered  — fix 1 + fix 2
  (baseline full_glada at 19.71% comes from Coding/results.json — no need to retrain)

All *stable* logic lives in the glada package. This notebook
intentionally inlines the experimental subclasses (PerGroupVIBModel,
StaggeredAlphaTrainer) and the custom sweep loop because (a) they're prototypes
testing reviewer feedback that may not pan out, and (b) the user explicitly
requested inline code where it differs from the package.

Build:
    python build_phase_vib_stagger.py
"""

