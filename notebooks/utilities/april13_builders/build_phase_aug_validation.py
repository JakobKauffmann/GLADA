"""
Builds phase_aug_validation.ipynb — a single-shot Colab notebook that
retrains the top GLADA configurations WITH MUSAN+RIR augmentation, to test
whether the negative-transfer finding survives stronger augmentation.

This is a DEFENSE-PREP experiment: COMPSAC reviewers and the defense committee
will reasonably ask whether per-group adversarial DA failed because the
training pipeline lacked MUSAN+RIR (standard in IB-CAAN's 4.61% ITW result).
This notebook produces controlled evidence one way or the other.

Configs retrained (all with full RawBoost + MUSAN + RIR augmentation):
  1. full_glada_aug         — wavlm-base-plus, full GLADA stack
  2. no_glada_aug           — wavlm-base-plus, single global DA (the baseline that beat full_glada)
  3. bb_wavlm-large_aug     — wavlm-large, full GLADA (best overall in original sweep)

Hypothesis under test: if augmentation rescues full_glada (eer < no_glada),
the negative-transfer claim is augmentation-confounded. If full_glada still
loses with augmentation, the negative-transfer claim is robust.

Build:
    python build_phase_aug_validation.py
Output:
    phase_aug_validation.ipynb
"""

