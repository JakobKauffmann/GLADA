"""Builds cross_dataset_eval_pgvib.ipynb — OOD cross-dataset evaluation of all PGVIB variants.

Purpose
-------
After training, each PGVIB variant's best checkpoint (identified by `best_eer` in
the phase results JSON) is loaded and evaluated on four held-out datasets:

  - ASVspoof 2021 LA   (codec/channel distortion)
  - ASVspoof 2021 DF   (codec post-processed deepfakes)
  - WaveFake           (neural vocoder diversity; LJSpeech bonafide)
  - CodecFake+         (codec-based LM TTS attacks)

Variants evaluated
------------------
From phase_pgvib_monolithic:
    monolithic_vib_s42 / s123 / s456

From phase_a_leaveout (seed-42 baselines; checkpoints in phase_a_leaveout):
    pergroup_vib_s42   (note: NOT in phase_pgvib_replicate — already trained in phase_a_leaveout)
    drop_vib_g0_s42    (same)

From phase_pgvib_replicate (extra seeds):
    pergroup_vib_s123 / s456
    drop_vib_g0_s123 / s456
    g0_only_xlsr_s42

From phase_pgvib_g0only:
    g0_only_vib_s42 / s123 / s456
    g0_only_large_s42

Missing checkpoints are skipped gracefully with a printed warning.

Output
------
/content/drive/MyDrive/Jakob/Experiments/cross_dataset_eval_pgvib_results.csv
Columns: variant, model_class, backbone, seed, dataset, eer, auc, n_samples, checkpoint_path

Build:
    cd Coding/notebooks/april13
    python build_cross_dataset_eval_pgvib.py
"""

