            "        continue",
            "",
            "    # Evaluate on each available OOD dataset.",
            "    for ds_name, loader in eval_loaders.items():",
            "        t0 = time.time()",
            "        try:",
            "            scores, labels = run_inference(model, loader, device, use_bf16=use_bf16)",
            "            metrics = compute_eer_with_ci(labels, scores, n_bootstrap=1000)",
            "            elapsed = time.time() - t0",
            "            print(",
            "                f'  {ds_name:<12s}: EER={metrics[\"eer\"]:.2f}%  '",
            "                f'CI=[{metrics[\"ci_low\"]:.2f}, {metrics[\"ci_high\"]:.2f}]  '",
            "                f'AUC={metrics[\"auc\"]:.4f}  n={metrics[\"acc\"]:.0f}%acc  '",
            "                f'({elapsed:.0f}s)'",
            "            )",
            "            row = {",
